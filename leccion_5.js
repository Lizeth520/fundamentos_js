// OPERADORES DE COMPARACION

let x = 5;

console.log(x == 6); //false
console.log(x == 5); //true

// Operador === compara el valor y el tipo de dato 

console.log(x === 5); //true
console.log(x === "5"); //false

// Operador != comparar si dos objetos son diferentes 
console.log(x != 8); //true
console.log(x != 5); //false

// Operador !== compara si dos objetos son diferentes y de diferente tipo de dato
console.log(x !== 5);   //false
console.log(x !== "5"); //true

//Operador > mayor que 
console.log(x > 9); //true
console.log(x > 5);  //true

//Operador < menor que
console.log(x < 10); //false
console.log(x < 5);  //false

//Operador >= mayor o igual que
console.log(x >= 5); //true
console.log(x >= 6); //false

//Operador <= menor o igual que
console.log(x <= 5); //true
console.log(x <= 4); //false    
console.log(x <= 6); //true

